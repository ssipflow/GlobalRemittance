-- 멱등성 키 도입(PR #16) 이전까지 Hibernate ddl-auto로 만들던 스키마를 그대로 옮긴 기준선이다.
-- ddl-auto로 만든 기존 파일 DB는 flyway 이력만 없으므로 baseline(0) 뒤에 이 스크립트가 다시 실행된다.
-- 그래서 모든 문장은 IF NOT EXISTS로 써서 이미 있는 테이블·인덱스를 건드리지 않는다.
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(128) NOT NULL,
    id_type ENUM('BUSINESS_NO', 'REG_NO') NOT NULL,
    id_value VARCHAR(128) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_user_id UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS remittances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    source_amount NUMERIC(22, 12) NOT NULL,
    target_amount NUMERIC(22, 12) NOT NULL,
    target_currency VARCHAR(3) NOT NULL,
    exchange_rate NUMERIC(22, 12) NOT NULL,
    fixed_fee NUMERIC(22, 12) NOT NULL,
    rated_fee NUMERIC(22, 12) NOT NULL,
    fee_ratio NUMERIC(22, 12) NOT NULL,
    usd_amount NUMERIC(22, 12) NOT NULL,
    usd_exchange_rate NUMERIC(22, 12) NOT NULL,
    expire_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    requested_time TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_remittances_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_remittances_user_requested
    ON remittances (user_id, requested_time);
